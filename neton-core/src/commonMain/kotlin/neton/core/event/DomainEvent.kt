package neton.core.event

import kotlin.reflect.KClass

/**
 * 领域事件标记。
 *
 * 事件由**发生方所在模块**定义，消费方模块订阅。发生方因此不需要认识任何消费方 ——
 * 这是它优于"直接回调某个业务端口"的地方：后者只能有一个实现，第二个消费方要接入
 * 就得挤进同一个实现里做分流，那个实现于是变成认识所有下游的中央调度器。
 */
interface DomainEvent

/**
 * 事件投递方式。决定监听者在什么时机执行、失败了怎么办。
 */
enum class DeliveryMode {

    /**
     * 与发布方同一事务内同步执行。抛异常会向上冒泡，发布方事务一并回滚。
     *
     * 用于**必须与发布方原子生效**的副作用：两者要么都成立、要么都不成立，
     * 中间状态在业务上不可接受。代价是一个有缺陷的监听者会阻断发布方主流程。
     */
    SYNC,

    /**
     * 同样在事务内执行，但异常被吞掉并记录，不影响发布方与其它监听者。
     *
     * 用于"做了更好、失败也不该拖垮主流程"的副作用。注意它仍占用主流程耗时。
     */
    BEST_EFFORT,

    /**
     * 事件在发布方事务内**落库**，由调度任务在事务提交后异步投递，失败按退避重试。
     *
     * 用于耗时的、或依赖外部系统（网络调用、第三方接口）的副作用：
     * 放进主事务会拉长事务持有时间、把外部系统的抖动变成本方的失败。
     *
     * 落库与发布方同事务，因此不存在"主流程成功了事件却丢了"；
     * 投递至少一次，**监听者必须自己保证幂等**。
     */
    RETRYABLE,
}

/**
 * 事件监听者。一个监听者订阅一种事件类型；同一事件可有任意多个监听者。
 *
 * 订阅父类型可收到其全部子类型（见 [DomainEventBus] 的匹配规则），
 * 因此把事件设计成密封层级时，既能整体订阅、也能只订阅其中一种。
 */
interface DomainEventListener<E : DomainEvent> {

    /**
     * 订阅的事件类型。
     *
     * 用 KClass 显式声明而不是靠泛型推断：Kotlin/Native 上没有完整反射，
     * 运行期拿不到被擦除的类型实参。
     */
    val eventType: KClass<E>

    /** 投递方式，默认与发布方同事务同步执行。 */
    val mode: DeliveryMode get() = DeliveryMode.SYNC

    /**
     * 监听者标识，[DeliveryMode.RETRYABLE] 下用于把落库事件路由回本监听者。
     *
     * **必须显式声明，且此后不可更改**：这个字符串会写进数据库，进程重启、版本升级之后
     * 还要能把积压的事件路由回来。曾经的默认实现是 `this::class.simpleName ?: toString()`，
     * 在 Kotlin/Native 上匿名对象的 simpleName 是 null，于是落库的是 `Foo@710ae18` ——
     * 一个内存地址，重启后必然对不上，那些行会永远投递不出去。
     *
     * 取值建议带上模块前缀，如 `"payment.wallet-recharge-paid"`，避免跨模块撞名。
     */
    val listenerId: String

    suspend fun onEvent(event: E)
}
